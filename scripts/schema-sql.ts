/**
 * Generates SQLite DDL straight from prisma/schema.prisma — no Prisma
 * engine binary needed. That matters because:
 *   - `prisma db push` can't talk to Turso (libSQL over the network), so
 *     the production schema has to be created with plain SQL anyway;
 *   - it also works in CI / sandboxes where Prisma's engine download is
 *     blocked.
 *
 * It supports exactly the subset of Prisma schema syntax this project
 * uses (scalar fields, enums, @id, @unique, @default, @updatedAt,
 * @relation, @@unique, @@index, @@map). If you add something exotic to
 * the schema, `npm run db:sql` fails loudly instead of guessing.
 *
 * Usage:   npm run db:sql            → writes prisma/schema.sql
 * Library: import { buildSchemaSql } from "./schema-sql"
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

type Field = {
  name: string;
  type: string;
  optional: boolean;
  list: boolean;
  attrs: string;
};
type Model = { name: string; table: string; fields: Field[]; attrs: string[] };

const SCALARS: Record<string, string> = {
  String: "TEXT",
  Int: "INTEGER",
  Boolean: "BOOLEAN",
  DateTime: "DATETIME",
  BigInt: "BIGINT",
  Float: "REAL",
};

function parse(schema: string) {
  const models: Model[] = [];
  const enums = new Map<string, string[]>();
  const lines = schema
    .split("\n")
    .map((l) => l.replace(/\/\/.*$/, "").trimEnd());

  for (let i = 0; i < lines.length; i++) {
    const head = lines[i].match(/^(model|enum)\s+(\w+)\s*\{/);
    if (!head) continue;
    const [, kind, name] = head;
    const body: string[] = [];
    for (i++; i < lines.length && lines[i].trim() !== "}"; i++) {
      if (lines[i].trim()) body.push(lines[i].trim());
    }
    if (kind === "enum") {
      enums.set(name, body);
      continue;
    }
    const model: Model = { name, table: name, fields: [], attrs: [] };
    for (const line of body) {
      if (line.startsWith("@@")) {
        model.attrs.push(line);
        const map = line.match(/^@@map\("([^"]+)"\)/);
        if (map) model.table = map[1];
        continue;
      }
      const m = line.match(/^(\w+)\s+(\w+)(\?|\[\])?\s*(.*)$/);
      if (!m) throw new Error(`Unsupported schema line: ${line}`);
      model.fields.push({
        name: m[1],
        type: m[2],
        optional: m[3] === "?",
        list: m[3] === "[]",
        attrs: m[4] ?? "",
      });
    }
    models.push(model);
  }
  return { models, enums };
}

const q = (s: string) => `"${s}"`;

function cols(list: string) {
  return list
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
}

export function buildSchemaSql(schemaPath = "prisma/schema.prisma"): string {
  const { models, enums } = parse(
    readFileSync(resolve(process.cwd(), schemaPath), "utf8"),
  );
  const modelByName = new Map(models.map((m) => [m.name, m]));
  const out: string[] = [
    "-- Generated by scripts/schema-sql.ts from prisma/schema.prisma.",
    "-- Do not edit by hand — change the schema and run `npm run db:sql`.",
    "",
  ];
  const indexes: string[] = [];

  for (const model of models) {
    const colDefs: string[] = [];
    const constraints: string[] = [];

    for (const f of model.fields) {
      const isScalar = f.type in SCALARS || enums.has(f.type);
      if (!isScalar || f.list) continue;

      const sqlType = SCALARS[f.type] ?? "TEXT";
      let def = `${q(f.name)} ${sqlType}`;
      const isId = /@id\b/.test(f.attrs);
      if (isId) def += " NOT NULL PRIMARY KEY";
      else if (!f.optional) def += " NOT NULL";

      const d = f.attrs.match(/@default\((.*?)\)(?=\s|$|@)/);
      if (d) {
        const v = d[1].trim();
        if (v === "now()") def += " DEFAULT CURRENT_TIMESTAMP";
        else if (v === "cuid()" || v === "uuid()") {
          /* generated by Prisma Client, no DB default */
        } else if (/^-?\d+(\.\d+)?$/.test(v)) def += ` DEFAULT ${v}`;
        else if (v === "true") def += " DEFAULT true";
        else if (v === "false") def += " DEFAULT false";
        else if (/^"[^"]*"$/.test(v)) def += ` DEFAULT '${v.slice(1, -1)}'`;
        else if (enums.get(f.type)?.includes(v)) def += ` DEFAULT '${v}'`;
        else throw new Error(`Unsupported @default(${v}) on ${model.name}.${f.name}`);
      }
      colDefs.push(def);

      if (/@unique\b/.test(f.attrs)) {
        indexes.push(
          `CREATE UNIQUE INDEX IF NOT EXISTS ${q(`${model.table}_${f.name}_key`)} ON ${q(model.table)}(${q(f.name)});`,
        );
      }
    }

    // Foreign keys — from @relation(fields: [...], references: [...]).
    for (const f of model.fields) {
      const rel = f.attrs.match(/@relation\((.*)\)/);
      if (!rel || !modelByName.has(f.type)) continue;
      const fields = rel[1].match(/fields:\s*\[([^\]]*)\]/);
      const refs = rel[1].match(/references:\s*\[([^\]]*)\]/);
      if (!fields || !refs) continue; // the "other side" of a relation
      const target = modelByName.get(f.type)!;
      const fk = cols(fields[1]);
      const onDelete = rel[1].match(/onDelete:\s*(\w+)/)?.[1];
      const action =
        onDelete === "Cascade"
          ? "CASCADE"
          : onDelete === "SetNull"
            ? "SET NULL"
            : onDelete === "Restrict"
              ? "RESTRICT"
              : f.optional
                ? "SET NULL"
                : "RESTRICT";
      constraints.push(
        `CONSTRAINT ${q(`${model.table}_${fk.join("_")}_fkey`)} FOREIGN KEY (${fk.map(q).join(", ")}) REFERENCES ${q(target.table)} (${cols(refs[1]).map(q).join(", ")}) ON DELETE ${action} ON UPDATE CASCADE`,
      );
    }

    for (const a of model.attrs) {
      const u = a.match(/^@@unique\(\[([^\]]*)\]/);
      const ix = a.match(/^@@index\(\[([^\]]*)\]/);
      if (u) {
        const c = cols(u[1]);
        indexes.push(
          `CREATE UNIQUE INDEX IF NOT EXISTS ${q(`${model.table}_${c.join("_")}_key`)} ON ${q(model.table)}(${c.map(q).join(", ")});`,
        );
      } else if (ix) {
        const c = cols(ix[1]);
        indexes.push(
          `CREATE INDEX IF NOT EXISTS ${q(`${model.table}_${c.join("_")}_idx`)} ON ${q(model.table)}(${c.map(q).join(", ")});`,
        );
      } else if (!a.startsWith("@@map")) {
        throw new Error(`Unsupported model attribute: ${a}`);
      }
    }

    out.push(
      `CREATE TABLE IF NOT EXISTS ${q(model.table)} (\n  ${[...colDefs, ...constraints].join(",\n  ")}\n);`,
      "",
    );
  }

  return [...out, ...indexes, ""].join("\n");
}

/** Column definitions per table, used by apply-schema.ts to add columns
 * that a newer schema introduced to an already-populated database. */
export function listColumns(schemaPath = "prisma/schema.prisma") {
  const sql = buildSchemaSql(schemaPath);
  const result = new Map<string, { name: string; def: string }[]>();
  for (const block of sql.split(/\n(?=CREATE TABLE)/)) {
    const t = block.match(/^CREATE TABLE IF NOT EXISTS "([^"]+)" \(\n([\s\S]*?)\n\);/);
    if (!t) continue;
    const columns = t[2]
      .split(",\n")
      .map((l) => l.trim())
      .filter((l) => l.startsWith('"'))
      .map((l) => ({ name: l.match(/^"([^"]+)"/)![1], def: l }));
    result.set(t[1], columns);
  }
  return result;
}

if (process.argv[1]?.endsWith("schema-sql.ts")) {
  const sql = buildSchemaSql();
  writeFileSync(resolve(process.cwd(), "prisma/schema.sql"), sql);
  console.log(`✓ prisma/schema.sql written (${sql.split("\n").length} lines)`);
}
